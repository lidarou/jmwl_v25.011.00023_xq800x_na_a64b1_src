/**
 * xor_16_check - 16BIT XOR check.
 *
 * Parameter:
 *  @buf: input check buf.
 *  @len: input buf len.
 *
 * Return:
 *  16BIT XOR check value.
 */
u16 xor_16_check(u8 *buf, u32 len)
{
    u16 chk, *ptr, data;
    u32 i, count;

    chk = 0;
    ptr = (u16 *)buf;
    count = len / 2;
    for (i = 0; i < count; i++) {
        chk ^= (*(u16 *)(ptr + i));
    }

    if (len > (count * 2)) {
        data = (*((u8 *)buf + len - 1) << 0x8) & 0xFF00;
        chk ^= data;
    }

    return chk;
}

