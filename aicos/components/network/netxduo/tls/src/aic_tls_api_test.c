void tls_receive_data(NX_TCPSERVER *server_ptr, NX_TCP_SESSION *session_ptr)
{
    NX_PACKET               *packet_ptr;
    NX_SECURE_TLS_SESSION   *tls_session;
    u8 buffer[128];
    ULONG bytes_received;
    int                     ret;

    server_ptr->nx_tcpserver_sessions->nx_tcp_session_tls_session =
        session_ptr->nx_tcp_session_tls_session;

    tls_session = &(session_ptr->nx_tcp_session_tls_session);
    ret = _nx_secure_tls_session_receive(tls_session, &packet_ptr,
                                        10 * NX_IP_PERIODIC_RATE);
    if (ret != NX_SUCCESS)
    {
        aicx_error(0x1cd4ab, "x", "TLS server receive data failed, error: 0x%x\n", ret);
        /* Return an error condition.  */
        return;
    }

    ret = nx_packet_data_extract_offset(packet_ptr, 0, (VOID*)((INT)buffer),
                                        128, &bytes_received);
    if (ret != NX_SUCCESS) {
        nx_secure_tls_packet_release(packet_ptr);
        return;
    }

    nx_secure_tls_packet_release(packet_ptr);

    ret = nx_secure_tls_packet_allocate(tls_session,
                                        tls_server_ip.nx_ip_default_packet_pool,
                                        &packet_ptr, NX_WAIT_FOREVER);
    if (ret != NX_SUCCESS) {
        aicx_error(0x027dad, "x", "[AT_TLS_TEST]: tls packet allocate fail ret is 0x%x\n", ret);
        return;
    } else {
        aicx_info(0x088dae, "p", "[AT_TLS_TEST]: allocate tls packet %p success\n", packet_ptr);
    }

    ret = nx_packet_data_append(packet_ptr, buffer, bytes_received,
                                tls_server_ip.nx_ip_default_packet_pool,
                                NX_WAIT_FOREVER);
    if (ret != NX_SUCCESS) {
        aicx_info(0x041b0f, "x", "[AT_TLS_TEST]: packet append fail ret is 0x%x\n", ret);
        return;
    } else {
        aicx_info(0x0ee85f, "p", "[AT_TLS_TEST]: append tls packet %p success\n", packet_ptr);
    }

    ret = nx_secure_tls_session_send(tls_session,
                                     packet_ptr,
                                     10 * NX_IP_PERIODIC_RATE);
    if (ret != NX_SUCCESS) {
        aicx_error(0x00584f, "pd", "[AT_TLS]: TLS send packet %p error, errno %d\n", packet_ptr, ret);
        nx_secure_tls_packet_release(packet_ptr);
        return;
    }
}

void tls_connection_end(NX_TCPSERVER *server_ptr, NX_TCP_SESSION *session_ptr)
{
    NX_TCP_SOCKET *tcp_socket;
    NX_SECURE_TLS_SESSION *tls_session;

    aicx_info(0x0ec4f1, "", "[AT_TLS_TEST]: tls connection end entry\n");
    tcp_socket = &(session_ptr->nx_tcp_session_socket);
    tls_session = &(session_ptr->nx_tcp_session_tls_session);

    /* End TLS session */
    nx_secure_tls_session_end(tls_session, 10 * NX_IP_PERIODIC_RATE);

    /* Disconnect from the current connection.  */
    nx_tcp_socket_disconnect(tcp_socket, 10 * NX_IP_PERIODIC_RATE);

    /* Unaccept the connection.  */
    nx_tcp_server_socket_unaccept(tcp_socket);
}

