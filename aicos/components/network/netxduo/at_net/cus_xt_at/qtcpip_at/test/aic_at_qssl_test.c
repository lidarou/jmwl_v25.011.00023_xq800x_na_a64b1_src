int aic_qssl_at_test_init(void)
{
    int status;

    if (tls_thread_server != AOS_INVALID_THREAD_ID)
        return 0;

    status = nx_packet_pool_create(&packet_pool, "TLS Server Packet Pool",
                                   1536, tls_packet_pool, 16896);
    if (status) {
        aicx_info(0x08dba7, "s", "[%s] Error in creating packet pool!\n", __func__);
    }
    status = nx_ip_create(&tls_ip, "TLS Server IP Instance",
                          IP_ADDRESS(1, 2, 3, 4), 0xFFFFFF00UL, &packet_pool,
                          _nx_ram_network_driver, tls_ip_instance_pool,
                          2048, 20);
    if (status) {
        aicx_info(0x16879c, "sx", "[%s] Error in creating tls IP Server Instance! status 0x%x\n", __func__, status);
    }

    nx_tcp_enable(&tls_ip);
    nx_udp_enable(&tls_ip);
    nx_arp_enable(&tls_ip, arp_cache_mem, sizeof(arp_cache_mem));
    bsd_initialize(&tls_ip, &packet_pool, tls_bsd_task_pool, 2048, 2);
    aic_init_dns_client();

    tls_thread_server = aos_create_thread("TLS Server Thread",
                    aic_tls_thread_server_entry, NULL,
                    SIZE_8K, 0, NULL, TCP_SERVER_TASK_PRIORITY,
                    AOS_AUTO_START);
    if (tls_thread_server == AOS_INVALID_THREAD_ID) {
        aicx_error(0x1a138f, "s", "%s:create TLS Server thread error\n", __func__);
        return -1;
    }else
        aicx_info(0x0e39db, "s", "%s:create TLS Server thread success\n", __func__);

    return 0;
}
