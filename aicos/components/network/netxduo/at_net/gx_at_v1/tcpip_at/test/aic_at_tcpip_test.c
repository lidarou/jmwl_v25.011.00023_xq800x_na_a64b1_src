void aic_tcp_thread_server_entry(void *thread_input)
{
    int tcp_sockfd, conn_sockfd = -1;
    int client_addr_len, index, iface_index, ret, i, len;
    NX_IP *client_ip;
    ULONG addr;
    struct sockaddr_in server_addr, client_addr;
    fd_set master_list, read_ready;
    char buffer[RECV_BUFFER_SIZE] = {'\0'};

    tcp_sockfd = anet_socket(AF_INET, SOCK_STREAM, NX_PROTOCOL_TCP);
    if (tcp_sockfd == -1) {
        aicx_error(0x059fa6, "sd", "%s:create socket error, errno %d\n", __func__, errno);
        return;
    } else {
        aicx_info(0x0e720a, "s", "%s:create socket success\n", __func__);
    }

    memset(&server_addr, 0, sizeof(struct sockaddr_in));

#ifdef AT_TLS_TEST
    client_ip = &tls_test_ip;
    addr = client_ip->nx_ip_interface[0].nx_interface_ip_address;
#else
    index = aic_get_wan_net_by_cid(ANET_DEFAULT_PDP_CID);
    iface_index = wan_net_list[index].wan_ifc_index;
    client_ip = wan_net_list[index].wan_ip_instance;
    addr = wan_net_list[index].wan_ipv4_address;
#endif

    server_addr.sin_family = AF_INET;
    server_addr.sin_addr.s_addr = htonl(addr);
    //server_addr.sin_addr.s_addr = addr;
    server_addr.sin_port = htons(TCP_SERVER_PORT);

    ret = anet_bind(tcp_sockfd, (struct sockaddr *)&server_addr,
                    sizeof(struct sockaddr_in));
    if (ret == -1) {
        aicx_error(0x112085, "sd", "%s: socket bind error, errno %d\n", __func__, errno);
        return;
    } else {
        aicx_info(0x1af9e1, "sd", "%s:bind socket success %d\n", __func__);
    }

    FD_ZERO(&master_list);
    FD_ZERO(&read_ready);
    FD_SET(tcp_sockfd, &master_list);

    ret = anet_listen(tcp_sockfd, 5);
    if (ret == -1) {
        aicx_error(0x11a8f4, "sd", "%s: socket listen error, errno %d\n", __func__, errno);
        return;
    } else {
        aicx_info(0x0e9cbe, "sd", "%s: socket listen success, ret %d\n", __func__, ret);
    }

    client_addr_len = sizeof(struct sockaddr_in);
    while (1) {
        read_ready = master_list;
        aos_sleep(20);
        ret = select(FD_SETSIZE, &read_ready, 0, 0, 0);
        if(ret == ERROR || ret == 0)
            continue;

        if(FD_ISSET(tcp_sockfd, &read_ready)) {
            conn_sockfd = anet_accept(tcp_sockfd,
                                      (struct sockaddr *)&client_addr,
                                      &client_addr_len);
            if (conn_sockfd == -1) {
                aicx_error(0x012120, "sd", "%s: socket accept error, errno %d\n",
                           __func__, errno);
                continue;
            } else {
                aicx_info(0x02e6e0, "sd", "%s: socket accept success, conn_socket %d\n",
                          __func__, conn_sockfd);
                FD_SET(conn_sockfd, &master_list);
            }
        }

        for (i = 0; i < NX_BSD_MAX_SOCKETS; i++) {
            if (((i + NX_BSD_SOCKFD_START) != tcp_sockfd) &&
                (FD_ISSET(i + NX_BSD_SOCKFD_START, &master_list)) &&
                (FD_ISSET(i + NX_BSD_SOCKFD_START, &read_ready))) {
                len = nx_bsd_get_socket_receive_data_length(i);
                aicx_info(0x15446e, "sd", "%s: recv data len %d\n", __func__, len);
                ret = anet_recv(i + NX_BSD_SOCKFD_START, buffer,
                                RECV_BUFFER_SIZE, MSG_DONTWAIT);
                if (ret == -1) {
                    aicx_error(0x116182, "sd", "%s: socket recv error, errno %d\n",
                               __func__, errno);
                    if(errno == EWOULDBLOCK)
                        continue;
                } else {
                    aicx_info(0x08b888, "ss", "%s: recv data %s\n", __func__, buffer);
                }

                ret = anet_send(i + NX_BSD_SOCKFD_START, buffer, ret, 0);
                if (ret == -1) {
                    aicx_error(0x1e749e, "sd", "%s: socket send error, errno %d\n", __func__, errno);
                    soc_close(i + NX_BSD_SOCKFD_START);
                    FD_CLR(i + NX_BSD_SOCKFD_START, &master_list);
                    continue;
                } else {
                    aicx_info(0x04828c, "ss", "%s: send data %s\n", __func__, buffer);
                }
                break;
            }
        }
    }

    soc_close(tcp_sockfd);
}

void aic_udp_thread_server_entry(void *thread_input)
{
    int udp_sockfd, len;
    int from_addr_len;
    int index, iface_index;
    NX_IP *client_ip;
    ULONG addr;
    int ret;
    u32 recv_data_len;
    struct sockaddr_in server_addr, from_addr;
    char buffer[RECV_BUFFER_SIZE] = {'\0'};

    //NX_PARAMETER_NOT_USED(thread_input);

    udp_sockfd = anet_socket(AF_INET, SOCK_DGRAM, NX_PROTOCOL_UDP);
    if (udp_sockfd == -1) {
        aicx_error(0x059fa6, "sd", "%s:create socket error, errno %d\n", __func__, errno);
        return;
    } else {
        aicx_info(0x0e720a, "s", "%s:create socket success\n", __func__);
    }

    memset(&server_addr, 0, sizeof(struct sockaddr_in));

#ifdef AT_TLS_TEST
    client_ip = &tls_test_ip;
    addr = client_ip->nx_ip_interface[0].nx_interface_ip_address;
#else
    index = aic_get_wan_net_by_cid(ANET_DEFAULT_PDP_CID);
    iface_index = wan_net_list[index].wan_ifc_index;
    client_ip = wan_net_list[index].wan_ip_instance;
    addr = wan_net_list[index].wan_ipv4_address;
#endif

    server_addr.sin_family = AF_INET;
    server_addr.sin_addr.s_addr = htonl(addr);
    //server_addr.sin_addr.s_addr = addr;
    server_addr.sin_port = htons(UDP_SERVER_PORT);
    aicx_info(0x1bca55, "sd", "%s:--udp server port %d\n", __func__, server_addr.sin_port);
    aicx_info(0x0588b4, "sx", "%s:--udp server addr 0x%x\n", __func__,
              server_addr.sin_addr.s_addr);

    ret = anet_bind(udp_sockfd, (struct sockaddr *)&server_addr,
                    sizeof(struct sockaddr_in));
    if (ret == -1) {
        aicx_error(0x112085, "sd", "%s: socket bind error, errno %d\n", __func__, errno);
        return;
    } else {
        aicx_info(0x1af9e1, "sd", "%s:bind socket success %d\n", __func__);
    }

    from_addr_len = sizeof(struct sockaddr_in);
    while (1) {
        //len = nx_bsd_get_socket_receive_data_length(udp_sockfd -
        //                                            NX_BSD_SOCKFD_START);
        getsockopt(udp_sockfd, SOL_SOCKET, SO_RXDATA, &recv_data_len, &len);
        if (recv_data_len == 0) {
            aos_sleep(100);
            continue;
        } else
            aicx_info(0x15446e, "sd", "%s: recv data len %d\n", __func__, recv_data_len);
        ret = anet_recvfrom(udp_sockfd, buffer, RECV_BUFFER_SIZE, 0,
                        (struct sockaddr *)&from_addr, &from_addr_len);
        if (ret == NX_SOC_ERROR) {
            aicx_error(0x116182, "sd", "%s: socket recv error, errno %d\n", __func__, errno);
            if(errno == EWOULDBLOCK)
                continue;
        } else {
             aicx_info(0x08b888, "ss", "%s: recv data %s\n", __func__, buffer);
        }

        ret = anet_sendto(udp_sockfd, buffer, ret, 0,
                          (struct sockaddr *)&from_addr, from_addr_len);
        if (ret == NX_SOC_ERROR) {
            aicx_error(0x1e749e, "sd", "%s: socket send error, errno %d\n", __func__, errno);
            continue;
        } else {
            aicx_info(0x04828c, "ss", "%s: send data %s\n", __func__, buffer);
        }
    }

    soc_close(udp_sockfd);
}

