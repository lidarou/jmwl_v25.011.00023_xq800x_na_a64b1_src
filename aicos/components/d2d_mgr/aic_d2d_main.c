static int aic_d2d_data_init(void)
{
    struct aic_d2d_data_cfg *d2d_cfg = &aic_d2d_cfg;

    memset(&aic_d2d_cfg, 0, sizeof(aic_d2d_cfg));

    d2d_cfg->send_thread_id = aos_create_thread("aic d2d send",
                                                aic_d2d_send_entry,
                                                d2d_cfg, SIZE_2K, 0, NULL, 36,
                                                AOS_AUTO_START);
    if (d2d_cfg->send_thread_id == AOS_INVALID_THREAD_ID) {
        app_logi("[D2D] send task create failed\n");
        return 0;
    }

    d2d_cfg->recv_thread_id = aos_create_thread("aic d2d recv",
                                                aic_d2d_recv_entry,
                                                d2d_cfg, SIZE_2K, 0, NULL, 8,
                                                AOS_AUTO_START);
    if (d2d_cfg->recv_thread_id == AOS_INVALID_THREAD_ID) {
        aos_delete_thread(d2d_cfg->send_thread_id);
        app_logi("[D2D] recv task create failed\n");
        return 0;
    }

    d2d_cfg->report_thread_id = aos_create_thread("aic d2d report",
                                                  aic_d2d_report_entry,
                                                  d2d_cfg, SIZE_2K, 0, NULL, 28,
                                                  AOS_AUTO_START);
    if (d2d_cfg->report_thread_id == AOS_INVALID_THREAD_ID) {
        aos_delete_thread(d2d_cfg->send_thread_id);
        aos_delete_thread(d2d_cfg->recv_thread_id);
        app_logi("[D2D] report task create failed\n");
        return 0;
    }

    d2d_cfg->d2d_event = aos_create_event("aic d2d event");
    if (d2d_cfg->d2d_event == AOS_NULL) {
        aos_delete_thread(d2d_cfg->send_thread_id);
        aos_delete_thread(d2d_cfg->recv_thread_id);
        aos_delete_thread(d2d_cfg->report_thread_id);
        app_logi("[D2D] event create failed\n");
        return 0;
    }

    d2d_cfg->d2d_queue = aos_create_queue("aic d2d queue", sizeof(u32), 16);
    if (d2d_cfg->d2d_queue == AOS_NULL) {
        aos_delete_thread(d2d_cfg->send_thread_id);
        aos_delete_thread(d2d_cfg->recv_thread_id);
        aos_delete_thread(d2d_cfg->report_thread_id);
        aos_delete_event(d2d_cfg->d2d_event);
        app_logi("[D2D] queue create failed\n");
        return 0;
    }

    d2d_cfg->mgr_thread_id = aos_create_thread("aic d2d mgr",
                                               aic_d2d_mgr_entry,
                                               d2d_cfg, SIZE_2K, 0, NULL, 28,
                                               AOS_AUTO_START);
    if (d2d_cfg->mgr_thread_id == AOS_INVALID_THREAD_ID) {
        aos_delete_thread(d2d_cfg->send_thread_id);
        aos_delete_thread(d2d_cfg->recv_thread_id);
        aos_delete_thread(d2d_cfg->report_thread_id);
        aos_delete_thread(d2d_cfg->mgr_thread_id);
        aos_delete_event(d2d_cfg->d2d_event);
        aos_delete_queue(d2d_cfg->d2d_queue);
        app_logi("[D2D] mgr task create failed\n");
        return 0;
    }

    d2d_cfg->d2d_send_mutex = aos_create_mutex("d2d send mutex");
    if (!d2d_cfg->d2d_send_mutex)
        app_logi("[D2D] create d2d send mutex fail\n");

    return 0;
}
AIC_APP_P2_INIT_EXPORT(aic_d2d_data_init);

