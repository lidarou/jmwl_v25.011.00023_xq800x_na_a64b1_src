int aic_handle_voice_stub_cmd(u32 at_port, u8 *cmd, u32 packet_size,
                              u32 packet_count, u32 period)
{
    struct aic_d2d_data_cfg *d2d_cfg = &aic_d2d_cfg;

    d2d_cfg->at_port = at_port;
    aic_network_enable_pdp_nic_capdump();
    aic_network_disable_pdp_nic_capdump();

    app_logi("[D2D] voice stub recv %s size %d count %d period %d\n", cmd,
             packet_size, packet_count, period);
    if (strcmp(cmd, "SEND") && strcmp(cmd, "RECV"))
        return -1;

    if (!strcmp(cmd, "SEND")) {
        d2d_cfg->dump_send = TRUE;
        return 0;
    } else {
        d2d_cfg->dump_recv = TRUE;
    }

    d2d_cfg->dump_recv_packet_size = 22;
    d2d_cfg->dump_recv_packet_count = packet_count;
    d2d_cfg->dump_recv_period = period;
    if (d2d_cfg->dump_recv_buf)
        free(d2d_cfg->dump_recv_buf);

    d2d_cfg->dump_recv_buf = malloc(d2d_cfg->dump_recv_packet_size);
    if (!d2d_cfg->dump_recv_buf)
        return -1;

    if (cmd)
        aos_set_event(d2d_cfg->d2d_event, AIC_D2D_SIMU_RECV_EVENT, AOS_OR);

    return AIC_SUCCESS;
}

