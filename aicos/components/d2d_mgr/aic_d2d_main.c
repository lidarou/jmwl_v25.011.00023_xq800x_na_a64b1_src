int aic_handle_send_msg_cmd(u32 at_port, s8 *message, u32 msg_size)
{
    int bytes_sent;
    struct sockaddr_ll destAddr;
    struct aic_d2d_data_cfg *d2d_cfg = &aic_d2d_cfg;

    if (!d2d_cfg->link_up || d2d_cfg->role == RECV_ONLY)
        return -1;

    if (d2d_cfg->dump_send) {
        aic_network_data_dump(message, msg_size);
        return 0;
    }

    memset(&destAddr, 0, sizeof(destAddr));
    destAddr.sll_family = PF_PACKET;
    destAddr.sll_ifindex = d2d_cfg->interface_index;

    d2d_cfg->at_port = at_port;

    app_logi("[D2D] msg size %d\n", msg_size);

    bytes_sent = sendto(d2d_cfg->send_socket, message, msg_size, 0,
                        (struct sockaddr *)&destAddr,
                        sizeof(destAddr));
    if (bytes_sent <= 0) {
        return -1;
    } else {
        if (d2d_cfg->dump_data)
            aic_network_data_dump(message, msg_size);
        d2d_cfg->send_bytes += bytes_sent;
        d2d_cfg->send_packet_count++;
    }

    return AIC_SUCCESS;
}

