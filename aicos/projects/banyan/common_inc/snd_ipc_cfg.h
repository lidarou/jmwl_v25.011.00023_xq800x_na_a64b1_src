
#include <aonram_mem_config.h>

#define PERIOD_SIZE_PCM         1920
#define PERIOD_SIZE_COMPR       2048
#define PERIOD_SIZE_AMR         64
#define PERIOD_SIZE_LOG         512
#define PERIOD_SIZE_DUMP        1028 /* 1024 + 4 */

#define SND_IPC_PERIOD_CNT      8
#define SND_IPC_BUF_HEAD_SIZE   32

#define SND_IPC_SHMEM_BASE      SND_IPC_REGION_BASE
#define SND_IPC_SHMEM_SIZE      SND_IPC_REGION_SIZE

/* size */
#define SND_IPC_SIZE_AP_CMD     0
#define SND_IPC_SIZE_CP_CMD     0
#define SND_IPC_SIZE_ASYNC      0
#define SND_IPC_SIZE_NV         0
#define SND_IPC_SIZE_PCM        0
#define SND_IPC_SIZE_COMPR      0
#define SND_IPC_SIZE_REC        0
#define SND_IPC_SIZE_UPLINK     (PERIOD_SIZE_AMR * SND_IPC_PERIOD_CNT + SND_IPC_BUF_HEAD_SIZE)
#define SND_IPC_SIZE_DOWNLINK   (PERIOD_SIZE_AMR * SND_IPC_PERIOD_CNT + SND_IPC_BUF_HEAD_SIZE)
#define SND_IPC_SIZE_LOG        0
#define SND_IPC_SIZE_DUMP       0

/* address in iram */
#define SND_IPC_MEM_AP_CMD      (SND_IPC_SHMEM_BASE)
#define SND_IPC_MEM_CP_CMD      (SND_IPC_MEM_AP_CMD + SND_IPC_SIZE_AP_CMD)
#define SND_IPC_MEM_ASYNC       (SND_IPC_MEM_CP_CMD + SND_IPC_SIZE_CP_CMD)
#define SND_IPC_MEM_NV          (SND_IPC_MEM_ASYNC + SND_IPC_SIZE_ASYNC)
#define SND_IPC_MEM_PCM         (SND_IPC_MEM_NV + SND_IPC_SIZE_NV)
#define SND_IPC_MEM_COMPR       (SND_IPC_MEM_PCM + SND_IPC_SIZE_PCM)
#define SND_IPC_MEM_REC         (SND_IPC_MEM_COMPR + SND_IPC_SIZE_COMPR)
#define SND_IPC_MEM_UPLINK      (SND_IPC_MEM_REC + SND_IPC_SIZE_REC)
#define SND_IPC_MEM_DOWNLINK    (SND_IPC_MEM_UPLINK + SND_IPC_SIZE_UPLINK)
#define SND_IPC_MEM_LOG         (SND_IPC_MEM_DOWNLINK + SND_IPC_SIZE_DOWNLINK)
#define SND_IPC_MEM_DUMP        (SND_IPC_MEM_LOG + SND_IPC_SIZE_LOG)

