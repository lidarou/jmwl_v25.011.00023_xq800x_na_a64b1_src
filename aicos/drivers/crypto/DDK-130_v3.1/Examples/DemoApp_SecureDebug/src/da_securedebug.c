/*----------------------------------------------------------------------------
 * AuthenticationService (RSA)
 */
static int
AuthenticationService(
        const uint8_t * NonceB_p,
        uint8_t * NonceA_p,
        ValAsymBigInt_t * Signature_p)
{
    int FuncReturnCode = -1;
    uint8_t Nonce[32];
    ValStatus_t funcres;
    ValAsymKey_t PrivateKey;
    ValAsymBigInt_t Modulus;
    ValAsymBigInt_t Exponent;
    ValAssetId_t PrivateKeyAssetId = VAL_ASSETID_INVALID;

    // Get the NonceA part
    funcres = val_RandomData(16, NonceA_p);
    if (funcres != VAL_SUCCESS)
    {
        LOG_CRIT(DA_PREFIX "FAILED: AuthenticationService NonceA generation.\n");
        goto func_error;
    }

    // Combine NonceA and NonceB
    memcpy(&Nonce[0],  NonceA_p, 16);
    memcpy(&Nonce[16], NonceB_p, 16);

    // Create private key asset
    funcres = val_AsymRsaPkcs1v15AllocPrivateKeyAsset(gl_KeyModulus_BitSize,
                                                      gl_KeyModulus_BitSize,
                                                      gl_HashAlgo, false, false,
                                                      &PrivateKeyAssetId);
    if (funcres != VAL_SUCCESS)
    {
        LOG_CRIT(DA_PREFIX "FAILED: AuthenticationService Key allocation\n");
        goto func_error;
    }

    if (gl_KeyModulus_BitSize == 1024)
    {
        Modulus.Data_p = gl_1KB_RsaKeyModulus;
        Modulus.ByteDataSize = sizeof(gl_1KB_RsaKeyModulus);
        Exponent.Data_p = gl_1KB_RsaKeyPrivateExponent;
        Exponent.ByteDataSize = sizeof(gl_1KB_RsaKeyPrivateExponent);
    }
    else if (gl_KeyModulus_BitSize == 2048)
    {
        Modulus.Data_p = gl_2KB_RsaKeyModulus;
        Modulus.ByteDataSize = sizeof(gl_2KB_RsaKeyModulus);
        Exponent.Data_p = gl_2KB_RsaKeyPrivateExponent;
        Exponent.ByteDataSize = sizeof(gl_2KB_RsaKeyPrivateExponent);
    }
    else
    {
        Modulus.Data_p = gl_3KB_RsaKeyModulus;
        Modulus.ByteDataSize = sizeof(gl_3KB_RsaKeyModulus);
        Exponent.Data_p = gl_3KB_RsaKeyPrivateExponent;
        Exponent.ByteDataSize = sizeof(gl_3KB_RsaKeyPrivateExponent);
    }

    funcres = val_AsymRsaLoadKeyAssetPlaintext(&Modulus, gl_KeyModulus_BitSize,
                                               &Exponent, gl_KeyModulus_BitSize,
                                               PrivateKeyAssetId, VAL_ASSETID_INVALID,
                                               NULL, 0, NULL, NULL);
    if (funcres != VAL_SUCCESS)
    {
        LOG_CRIT(DA_PREFIX "FAILED: AuthenticationService Key allocation\n");
        goto func_error;
    }

    funcres = val_AsymInitKey(PrivateKeyAssetId, VAL_ASSETID_INVALID,
                              gl_KeyModulus_BitSize, gl_HashAlgo,
                              &PrivateKey);
    if (funcres != VAL_SUCCESS)
    {
        LOG_CRIT(DA_PREFIX "FAILED: AuthenticationService Key initialization\n");
        goto func_error;
    }

    // Sign the Nonce
    Signature_p->Data_p = gl_SignatureBuffer;
    Signature_p->ByteDataSize = sizeof(gl_SignatureBuffer);
    funcres = val_AsymRsaPkcs1v15Sign(&PrivateKey,
                                      Signature_p,
                                      Nonce, 32, NULL, false);
    if (funcres != VAL_SUCCESS)
    {
        LOG_CRIT(DA_PREFIX "FAILED: AuthenticationService Signing of Nonce (A+B)\n");
    }
    else
    {
        FuncReturnCode = 0;
    }

func_error:
    if (PrivateKeyAssetId != VAL_ASSETID_INVALID)
    {
        (void)val_AssetFree(PrivateKeyAssetId);
    }

    return FuncReturnCode;
}
